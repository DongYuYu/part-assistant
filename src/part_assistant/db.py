"""SQLite schema and connection helper for the fake factory data.

All data in this database is synthetic (generated by `part_assistant.seed`).
"""

import os
import sqlite3
from pathlib import Path

DEFAULT_DB_PATH = Path(os.environ.get("PART_DB_PATH", "data/processed/factory.db"))

SCHEMA = """
CREATE TABLE IF NOT EXISTS parts (
    part_no     TEXT PRIMARY KEY,
    name        TEXT NOT NULL,
    category    TEXT NOT NULL CHECK (category IN ('psu', 'fan', 'connector', 'capacitor')),
    spec        TEXT NOT NULL,
    vendor_mpn  TEXT,  -- manufacturer part number; links a part to its public datasheet
    lifecycle   TEXT NOT NULL CHECK (lifecycle IN ('active', 'nrnd', 'eol'))
);

CREATE TABLE IF NOT EXISTS inventory (
    part_no      TEXT NOT NULL REFERENCES parts(part_no),
    warehouse    TEXT NOT NULL,
    qty_on_hand  INTEGER NOT NULL CHECK (qty_on_hand >= 0),
    qty_reserved INTEGER NOT NULL CHECK (qty_reserved >= 0 AND qty_reserved <= qty_on_hand),
    updated_at   TEXT NOT NULL,
    PRIMARY KEY (part_no, warehouse)
);

CREATE TABLE IF NOT EXISTS tickets (
    ticket_id       TEXT PRIMARY KEY,
    idempotency_key TEXT NOT NULL UNIQUE,  -- last line of defense against duplicate tickets
    part_no         TEXT REFERENCES parts(part_no),
    title           TEXT NOT NULL,
    description     TEXT NOT NULL,
    severity        TEXT NOT NULL CHECK (severity IN ('low', 'medium', 'high')),
    status          TEXT NOT NULL CHECK (status IN ('pending_approval', 'open', 'closed')),
    created_at      TEXT NOT NULL
);
"""


def connect(path: str | Path = DEFAULT_DB_PATH) -> sqlite3.Connection:
    """Open the database with foreign keys enforced and dict-like rows."""
    path = Path(path)
    if str(path) != ":memory:":
        path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row  # rows behave like dicts: row["part_no"]
    conn.execute("PRAGMA foreign_keys = ON")  # SQLite does NOT enforce FKs by default
    return conn


def init_schema(conn: sqlite3.Connection) -> None:
    conn.executescript(SCHEMA)
